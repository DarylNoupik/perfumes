create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null,
  category text not null default '',
  description text not null default '',
  notes text[] not null default '{}',
  size text not null default '',
  icon text not null default '',
  image_url text,
  featured boolean not null default false,
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0)
);

create table public.product_tracking (
  product_id bigint primary key references public.products(id) on delete cascade,
  code text unique,
  audience text not null default 'Non renseigné'
    check (audience in ('Femme', 'Homme', 'Mixte', 'Non renseigné')),
  purchase_price integer check (purchase_price >= 0),
  fees integer not null default 0 check (fees >= 0),
  opening_stock integer check (opening_stock >= 0)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id),
  customer_name text not null,
  customer_phone text not null,
  address text not null,
  status text not null default 'en attente'
    check (status in ('en attente', 'en cours', 'livré', 'annulé')),
  payment_method text not null,
  placed_at timestamptz not null default now()
);
create index orders_customer_id_idx on public.orders(customer_id);

create table public.order_items (
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  quantity integer not null check (quantity > 0),
  planned_price integer not null check (planned_price >= 0),
  primary key (order_id, product_id)
);
create index order_items_product_id_idx on public.order_items(product_id);

create table public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  source_key text unique,
  kind text not null check (kind in ('receipt', 'sale')),
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  product_code text,
  audience text,
  occurred_on date,
  quantity integer not null check (quantity > 0),
  planned_price integer check (planned_price >= 0),
  unit_price integer not null check (unit_price >= 0),
  unit_cost integer check (unit_cost >= 0),
  note text not null default ''
);
create index stock_movements_product_id_idx on public.stock_movements(product_id);

create table public.order_item_tracking (
  order_id uuid not null,
  product_id bigint not null,
  actual_price integer check (actual_price >= 0),
  unit_cost integer check (unit_cost >= 0),
  primary key (order_id, product_id),
  foreign key (order_id, product_id) references public.order_items(order_id, product_id) on delete cascade
);

