  for select to authenticated
  using (customer_id = (select auth.uid()) or
    (select auth.jwt() -> 'app_metadata' ->> 'role') in ('admin', 'vendor'));

create policy order_items_read_with_order on public.order_items
  for select to authenticated using (
    exists (select 1 from public.orders where orders.id = order_items.order_id)
  );

create function public.place_shop_order(
  customer_name text, customer_phone text, delivery_address text,
  payment_method text, items jsonb
) returns uuid
language plpgsql security definer
set search_path = ''
as $$
declare
  buyer uuid := auth.uid();
  new_order uuid;
  line record;
begin
  if buyer is null then
    raise exception 'Une connexion est requise' using errcode = '42501';
  end if;
  if nullif(trim(customer_name), '') is null or nullif(trim(customer_phone), '') is null
    or nullif(trim(delivery_address), '') is null
    or payment_method is null or payment_method not in ('Mobile Money', 'WhatsApp')
    or jsonb_typeof(items) is distinct from 'array' then
    raise exception 'Commande invalide' using errcode = '22023';
  end if;
  if jsonb_array_length(items) not between 1 and 100 then
    raise exception 'Panier invalide' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_to_recordset(items) as i(product_id bigint, quantity integer)
    where i.product_id is null or i.quantity is null or i.quantity < 1
  ) then
    raise exception 'Quantité ou produit invalide' using errcode = '22023';
  end if;

  insert into public.orders(customer_id, customer_name, customer_phone, address, payment_method)
  values (buyer, trim(customer_name), trim(customer_phone), trim(delivery_address), payment_method)
  returning id into new_order;

  for line in
    select i.product_id, sum(i.quantity) as quantity
    from jsonb_to_recordset(items) as i(product_id bigint, quantity integer)
    group by i.product_id
    order by i.product_id
  loop
    with reserved as (
      update public.products as p set stock = p.stock - line.quantity
      where p.id = line.product_id and p.stock >= line.quantity
      returning p.id, p.name, p.price
    )
    insert into public.order_items(order_id, product_id, product_name, quantity, planned_price)
    select new_order, p.id, p.name, line.quantity, p.price from reserved as p;
    if not found then
      raise exception 'Stock insuffisant pour le produit %', line.product_id using errcode = '22023';
    end if;

    insert into public.order_item_tracking(order_id, product_id, unit_cost)
    select new_order, t.product_id, t.purchase_price + t.fees
    from public.product_tracking as t where t.product_id = line.product_id;
  end loop;
  return new_order;
end;
$$;

revoke all on function public.place_shop_order(text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.place_shop_order(text, text, text, text, jsonb) to authenticated;
